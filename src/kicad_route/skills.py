"""Agent skills that follow the installed KRT release.

KRT (KiCadRoutingTools) ships routing-analysis skills. `kicad-route update`
regenerates adapted copies under STATE/vendor/skills/krt-*: the upstream SKILL.md
body verbatim, a replaced frontmatter (prefixed name, short description) and a
marked header that maps upstream's paths and retry advice onto kicad-route. The
upstream LICENSE and an UPSTREAM.json provenance record sit beside each SKILL.md.
The tools stay in the KRT checkout, which the header names.

They are generated, not committed, because they track whichever KRT release is
installed. Discovery links go where agents look for user-level skills (the same
places scripts/install.sh links the kicad-route skill); an existing path that is
not one of these links is never replaced.
"""
import hashlib
import json
import os
import subprocess
from pathlib import Path

from .common import STATE

SKILLS_DIR = STATE / "vendor" / "skills"
PREFIX = "krt-"
KRT_SKILLS = {
    "diagnose-routing-failures": ("Use after a kicad-route attempt leaves nets unrouted or fails validation: "
                                  "root-cause it from the run directory and plan the next attempt; see body "
                                  "for the kicad-route mapping."),
    "review-routed-board": ("Use to review a kicad-route candidate beyond its native grading (orphan stubs, "
                            "dangling vias, length/diff-pair/return-via checks); see body for paths and the "
                            "kicad-route mapping."),
}
HEADER = """<!-- BEGIN kicad-route adaptation (generated by `kicad-route update`; do not edit) -->
> **kicad-route adaptation.** Upstream: KiCadRoutingTools `{describe}` (`{commit}`),
> skill `{skill}`, MIT licence (see `LICENSE`). The text below the marker is upstream's,
> verbatim. Where it conflicts with this header, this header wins. Load the
> `kicad-route` skill first: it defines how routing attempts run and are graded.
>
> - **Paths.** Upstream's `py_router/…` and `py_tools/…` are under `{krt}/`; run them
>   as `{python} -X utf8 {krt}/py_router/<tool>.py`.
> - **Logs.** Upstream's `/tmp/<step>.txt` captures are already in each run directory
>   `<OUT>/runs/<project>/<label>/<stamp>/` (OUT defaults to `./build/kicad-route`):
>   `work/krt.log` (full KRT output, including `JSON_SUMMARY`), `work/krt-out/summary.json`,
>   `work/freerouting.log` and `work/freerouting-result.json`. The candidate is
>   `candidate/<project>/<board>`; the untouched input is `reference/<project>/<board>`.
> - **Retries go through the wrapper.** Express every retry as `kicad-route run …` (or
>   the project's own make target), passing KRT flags with `--backend-arg` and `KICAD_*`
>   knobs with `--backend-env`. Never route the real design in place, and never run KRT
>   on files outside a run directory.
> - **No relaxation.** Do not use or suggest `--escalation board|fab`, `--fab-tier
>   advanced|auto`, `--fab-overrides` that lower a floor, `--clearance-ceiling`,
>   `--relax-drc-severities`, lowering `--track-width`/`--via-size`/`--clearance` below the
>   net class, or re-enabling `KICAD_TERMINAL_ESCALATION`. Tightening is fine.
> - **Grading.** The pass/fail verdict is the run's `result.json`: KiCad's own DRC with
>   schematic parity against the input's unchanged rules, plus the preservation checks.
>   KRT's `check_*` tools are supplementary diagnostics; run them on the candidate (its
>   `.kicad_pro` is the original). Ignore upstream steps about the plugin GUI.
<!-- END kicad-route adaptation -->

"""


def discovery_dirs():
    return [Path.home() / ".agents" / "skills",
            Path(os.environ.get("CODEX_HOME") or Path.home() / ".codex") / "skills",
            Path.home() / ".claude" / "skills"]


def split_frontmatter(text):
    if not text.startswith("---\n"):
        raise ValueError("SKILL.md has no frontmatter")
    end = text.index("\n---\n", 4)
    return text[4:end], text[end + 5:]


def render(krt_dir, krt_venv, dest_root):
    """Write the adapted skills under dest_root; [] when KRT is not installed."""
    if not (krt_dir / ".claude" / "skills").is_dir():
        return []

    def git(*args):
        r = subprocess.run(["git", "-C", str(krt_dir), *args], capture_output=True, text=True)
        return r.stdout.strip() if r.returncode == 0 else None

    prov = {"describe": git("describe", "--tags", "--always"), "commit": git("rev-parse", "HEAD")}
    license_text = (krt_dir / "LICENSE").read_text()
    names = []
    for skill, desc in KRT_SKILLS.items():
        raw = (krt_dir / ".claude" / "skills" / skill / "SKILL.md").read_text()
        _, body = split_frontmatter(raw)
        name = PREFIX + skill
        out = dest_root / name
        out.mkdir(parents=True, exist_ok=True)
        (out / "SKILL.md").write_text(
            f"---\nname: {name}\ndescription: {json.dumps(desc)}\n---\n\n"
            + HEADER.format(skill=skill, krt=krt_dir, python=krt_venv / "bin" / "python", **prov)
            + body.lstrip("\n"))
        (out / "LICENSE").write_text(license_text)
        (out / "UPSTREAM.json").write_text(json.dumps({
            "upstream": "https://github.com/drandyhaas/KiCadRoutingTools",
            "describe": prov["describe"], "commit": prov["commit"],
            "skill_subdir": f".claude/skills/{skill}",
            "upstream_skill_md_sha256": hashlib.sha256(raw.encode()).hexdigest(),
            "license": "MIT",
            "update": "follows the installed KRT release; regenerated by `kicad-route update`",
            "adaptations": [
                f"frontmatter name {skill!r} -> {name!r} (avoid generic skill-name collisions)",
                "frontmatter description replaced with a short house description",
                "kicad-route header inserted above the verbatim upstream body",
                f"tools stay in {krt_dir} (not copied)",
            ],
        }, indent=2) + "\n")
        names.append(name)
    return names


def link(source, destination):
    """Create or keep a discovery symlink; never replace anything else."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.is_symlink():
        if destination.resolve() == source.resolve():
            return "kept"
        destination.unlink()
    elif destination.exists():
        return f"skipped ({destination} exists and is not a link)"
    destination.symlink_to(source)
    return "linked"


def sync(krt_dir, krt_venv):
    names = render(krt_dir, krt_venv, SKILLS_DIR)
    if not names:
        return "skills: KRT is not installed; krt-* skills not generated"
    notes = []
    for name in names:
        for d in discovery_dirs():
            r = link(SKILLS_DIR / name, d / name)
            if r.startswith("skipped"):
                notes.append(r)
    return f"skills: generated {', '.join(names)} in {SKILLS_DIR}" + (f"; {'; '.join(notes)}" if notes else "")
